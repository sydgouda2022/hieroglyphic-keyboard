"""Deterministic converter of *already verified* and permission-cleared normalized records.

This is NOT a source scraper and does not certify that a dataset is comprehensive.
Adapter modules for KELLIA/TLA/AED/AES/ORAEC must preserve original IDs and
supply a matching source-manifest with license/provenance before publication.
Use Python 3.12+. No network requests or runtime user data collection.
"""
from __future__ import annotations
import argparse
import hashlib
import json
import unicodedata
from pathlib import Path

REQUIRED = ('id', 'language', 'surface', 'sourceId', 'sourceRef')
COPYABLE = ('id', 'language', 'surface', 'sourceId', 'sourceRef', 'stage',
            'dialect', 'lemmaId', 'formId', 'morphology', 'partOfSpeech',
            'frequency', 'previous')


def key(surface: str, lang: str) -> str:
    if lang == 'egy':
        return unicodedata.normalize('NFC', surface)
    if lang == 'cop':
        return ''.join(c for c in unicodedata.normalize('NFD', surface).lower()
                       if not unicodedata.category(c).startswith('M'))
    raise ValueError('Unsupported language')


def has_native_writing(s: str, language: str) -> bool:
    if language == 'egy':
        return any(0x13000 <= ord(c) <= 0x143FF for c in s)
    return any(0x2C80 <= ord(c) <= 0x2CFF or 0x03E2 <= ord(c) <= 0x03EF for c in s)


def compile_records(records: list[dict], manifest: dict, lang: str) -> dict:
    if manifest.get('schema') != 1 or not isinstance(manifest.get('sources'), list):
        raise ValueError('Source manifest missing or invalid')
    sources = {}
    for s in manifest['sources']:
        for field in ('id', 'version', 'license', 'attribution', 'url', 'sha256'):
            if not s.get(field):
                raise ValueError(f'Source manifest missing {field}')
        if s['id'] in sources:
            raise ValueError('Duplicate source id')
        sources[s['id']] = s
    result = []
    seen = set()
    for r in records:
        if any(not isinstance(r.get(k), str) or not r[k] for k in REQUIRED):
            raise ValueError('Missing required record field')
        if r['language'] != lang:
            continue
        if r['id'] in seen:
            raise ValueError('Duplicate spelling id')
        seen.add(r['id'])
        if r['sourceId'] not in sources:
            raise ValueError('Unregistered source')
        if r.get('attested') is not True:
            raise ValueError('Only actually attested records may enter the dictionary')
        if lang == 'egy' and not r.get('stage'):
            raise ValueError('Egyptian writing stage is required')
        if lang == 'cop' and not r.get('dialect'):
            raise ValueError('Coptic dialect is required')
        if not has_native_writing(r['surface'], lang):
            raise ValueError('Record has no native-script signs or letters')
        if 'frequency' in r and (isinstance(r['frequency'], bool) or
                                 not isinstance(r['frequency'], int) or r['frequency'] < 0):
            raise ValueError('Frequency must be a nonnegative observed integer')
        obj = {field: r[field] for field in COPYABLE if field in r}
        obj['key'] = key(obj['surface'], lang)
        obj['attested'] = True
        result.append(obj)
    if not result:
        raise ValueError('No licensed entries for selected language')
    result.sort(key=lambda r: (r['key'], r['id']))
    return {'schema': 1, 'language': lang, 'coverage': 'UNVERIFIED',
            'sources': list(sources), 'rows': result}


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--records', required=True, type=Path,
                   help='Normalized attested JSONL, generated by source-specific adapters')
    p.add_argument('--manifest', required=True, type=Path,
                   help='Pinned source version/sha256/license manifest')
    p.add_argument('--language', required=True, choices=['egy', 'cop'])
    p.add_argument('--out', required=True, type=Path)
    args = p.parse_args()
    manifest = json.loads(args.manifest.read_text(encoding='utf-8'))
    records = [json.loads(s) for s in args.records.read_text(encoding='utf-8').splitlines() if s.strip()]
    pack = compile_records(records, manifest, args.language)
    encoded = (json.dumps(pack, ensure_ascii=False, separators=(',', ':'))+'\n').encode('utf-8')
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_bytes(encoded)
    print(json.dumps({'language': args.language, 'entries': len(pack['rows']),
                      'sha256': hashlib.sha256(encoded).hexdigest(),
                      'coverage': pack['coverage']}))


if __name__ == '__main__':
    main()
